import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const sourcePath = path.join(
  root,
  "models",
  "state-rent",
  "1.0.0-candidate.1.json",
);
const outputPath = path.join(root, "app", "preview", "manifest.ts");
const source = JSON.parse(fs.readFileSync(sourcePath, "utf8"));

// Keep this allowlist deliberately narrow. In particular, never expose repairs,
// runtime/source hashes, paths, formulas, or review metadata to the browser.
const fieldKeys = [
  "id",
  "cell",
  "label",
  "unit",
  "group",
  "type",
  "default",
  "required",
  "blankOnNew",
  "options",
  "year",
  "scheduleRow",
  "min",
  "max",
  "exclusiveMin",
  "exclusiveMax",
  "integer",
];
const fields = source.fields.map((field) =>
  Object.fromEntries(
    fieldKeys
      .filter((key) => Object.hasOwn(field, key))
      .map((key) => [key, field[key]]),
  ),
);
const manifest = {
  id: source.id,
  version: source.version,
  name: source.name,
  description: source.description,
  releaseStatus: source.releaseStatus,
  groups: source.groups.map(({ id, name }) => ({ id, name })),
  fields,
};

const contents = `// Generated by scripts/generate-preview-manifest.mjs. Do not edit by hand.\nexport const previewManifest = ${JSON.stringify(manifest, null, 2)} as const;\n`;
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, contents);
console.log(
  `Wrote ${fields.length} sanitized fields to ${path.relative(root, outputPath)}`,
);
